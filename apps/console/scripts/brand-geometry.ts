/**
 * Write src/components/brand/mark-geometry.ts from an SVG (default
 * assets/brand/mark.svg). Run by scripts/brand-geometry.sh, which
 * render-brand.sh calls. `bun scripts/brand-geometry.ts [in.svg] [out.ts]`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseMark } from "../src/components/brand/parse-mark";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const input = process.argv[2] ?? join(root, "assets", "brand", "mark.svg");
const output = process.argv[3] ?? join(here, "..", "src", "components", "brand", "mark-geometry.ts");
const mark = parseMark(readFileSync(input, "utf8"));
const source = relative(root, input).startsWith("..") ? input : relative(root, input);
writeFileSync(
  output,
  `// Generated by scripts/brand-geometry.sh from ${source}.\n` +
    `// Do not edit: change the SVG and run scripts/render-brand.sh.\n` +
    `import type { Mark } from "./parse-mark";\n\n` +
    `export const MARK: Mark = ${JSON.stringify(mark, null, 2)};\n`,
);
console.log(`wrote ${relative(root, output)} (${mark.shapes.length} shapes, ${mark.masks.length} masks)`);
