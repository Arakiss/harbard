//! `harbard huginn`: views, the components an agent shows the operator
//! instead of a sentence, and the check a view passes before it is attached.
//!
//! The catalog is written once, in TypeScript (`packages/huginn`). This
//! module embeds what that package generates (`huginn/catalog.json`,
//! `huginn/guide.md`) and applies the same rules, so an agent learns what is
//! wrong with a view when it can still fix it. The console validates again
//! before rendering; this check is for the agent's sake, not the last wall.
//! `packages/huginn/fixtures` runs through both validators, and a test on the
//! package side fails if the schemas use a keyword [`conforms`] does not know.

use harbard_core::brief::hidden_chars_in;
use serde::Deserialize;
use serde_json::{Map, Value, json};
use std::collections::{HashMap, HashSet};
use std::io::Read;
use std::path::Path;
use std::sync::OnceLock;

use crate::cli::HuginnAction;

const CATALOG: &str = include_str!("huginn/catalog.json");
const GUIDE: &str = include_str!("huginn/guide.md");
const MAX_ISSUES: usize = 20;

#[derive(Deserialize)]
struct Catalog {
    limits: Limits,
    components: HashMap<String, Component>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Limits {
    bytes: usize,
    elements: usize,
    depth: usize,
    expression_depth: usize,
    state_depth: usize,
    repeat_items: usize,
    repeat_elements: usize,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Component {
    children: ChildRule,
    inside_form: bool,
    answers: bool,
    files: Vec<String>,
    lengths: Vec<LengthRule>,
    fixed: Fixed,
    props: Value,
}

/// Props that must be literal: every one (`"all"`) or these names.
#[derive(Deserialize)]
#[serde(untagged)]
enum Fixed {
    All(FixedAll),
    Names(Vec<String>),
}

#[derive(Deserialize)]
#[serde(rename_all = "lowercase")]
enum FixedAll {
    All,
}

impl Fixed {
    fn is_all(&self) -> bool {
        matches!(self, Fixed::All(_))
    }

    fn holds(&self, name: &str) -> bool {
        match self {
            Fixed::All(_) => true,
            Fixed::Names(names) => names.iter().any(|n| n == name),
        }
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "lowercase")]
enum Arity {
    None,
    Some,
}

#[derive(Deserialize)]
#[serde(untagged)]
enum ChildRule {
    Arity(Arity),
    Match {
        #[serde(rename = "sameLengthAs")]
        same_length_as: String,
    },
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct LengthRule {
    list: String,
    field: Option<String>,
    #[serde(default)]
    whole: bool,
    same_length_as: String,
}

fn catalog() -> &'static Catalog {
    static PARSED: OnceLock<Catalog> = OnceLock::new();
    PARSED.get_or_init(|| serde_json::from_str(CATALOG).expect("generated by packages/huginn"))
}

/// One broken rule. `code` matches the TypeScript validator's.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Issue {
    pub code: &'static str,
    pub element: Option<String>,
    pub message: String,
}

fn issue(code: &'static str, element: Option<&str>, message: String) -> Issue {
    Issue {
        code,
        element: element.map(str::to_string),
        message,
    }
}

/// One line per issue, for a refusal an agent reads.
pub fn describe(issues: &[Issue]) -> String {
    issues
        .iter()
        .map(|i| match &i.element {
            Some(e) => format!("{} ({e}): {}", i.code, i.message),
            None => format!("{}: {}", i.code, i.message),
        })
        .collect::<Vec<_>>()
        .join("; ")
}

fn format_holds(format: &str, s: &str) -> bool {
    match format {
        "http_url" => {
            let lower = s.to_ascii_lowercase();
            let rest = lower
                .strip_prefix("https://")
                .or_else(|| lower.strip_prefix("http://"));
            rest.is_some_and(|r| !r.is_empty() && !r.chars().any(char::is_whitespace))
        }
        "file_name" => {
            let mut bytes = s.bytes();
            let word = |b: u8| b.is_ascii_alphanumeric() || matches!(b, b'_' | b'-');
            s.len() <= 100 && bytes.next().is_some_and(word) && bytes.all(|b| word(b) || b == b'.')
        }
        "iso_date" => {
            let b = s.as_bytes();
            b.len() == 10
                && b.iter().enumerate().all(|(i, c)| {
                    if i == 4 || i == 7 {
                        *c == b'-'
                    } else {
                        c.is_ascii_digit()
                    }
                })
        }
        "answer_id" => answer_id(s),
        "state_path" => state_path(s),
        _ => false,
    }
}

fn answer_id(s: &str) -> bool {
    let mut bytes = s.bytes();
    s.len() <= 64
        && bytes.next().is_some_and(|b| b.is_ascii_alphabetic())
        && bytes.all(|b| b.is_ascii_alphanumeric() || matches!(b, b'_' | b'-'))
}

/// Every segment starts with a letter or digit, which already rules out
/// `__proto__`; the other two names would still reach `Object.prototype`.
fn state_path(s: &str) -> bool {
    let Some(rest) = s.strip_prefix('/') else {
        return false;
    };
    s.len() <= 128
        && rest.split('/').all(|segment| {
            let mut bytes = segment.bytes();
            bytes.next().is_some_and(|b| b.is_ascii_alphanumeric())
                && bytes.all(|b| b.is_ascii_alphanumeric() || matches!(b, b'_' | b'-'))
                && !matches!(segment, "constructor" | "prototype")
        })
}

fn item_path(s: &str) -> bool {
    s.is_empty() || state_path(&format!("/{s}"))
}

/// Whether a checked expression or condition reads the repeat item.
type Checked = Result<bool, String>;

fn is_expression(value: &Value) -> bool {
    value
        .as_object()
        .is_some_and(|fields| fields.keys().any(|k| k.starts_with('$')))
}

fn is_scalar(value: &Value) -> bool {
    !value.is_array() && !value.is_object()
}

fn is_state_ref(value: &Value) -> bool {
    value.as_object().is_some_and(|fields| {
        fields.len() == 1
            && fields
                .get("$state")
                .and_then(Value::as_str)
                .is_some_and(state_path)
    })
}

fn check_single(value: &Value) -> Checked {
    let fields = value.as_object().ok_or("a condition is an object")?;
    let sources: Vec<&str> = ["$state", "$item", "$index"]
        .into_iter()
        .filter(|k| fields.contains_key(*k))
        .collect();
    let [source] = sources.as_slice() else {
        return Err("a condition reads one of $state, $item or $index".into());
    };
    let read = &fields[*source];
    let sound = match *source {
        "$state" => read.as_str().is_some_and(state_path),
        "$item" => read.as_str().is_some_and(item_path),
        _ => read == &Value::Bool(true),
    };
    if !sound {
        return Err(format!("{source} has a value it cannot read"));
    }
    for (key, operand) in fields {
        if key == source {
            continue;
        }
        let fits = match key.as_str() {
            "not" => operand == &Value::Bool(true),
            "eq" | "neq" => is_scalar(operand) || is_state_ref(operand),
            "gt" | "gte" | "lt" | "lte" => operand.is_number() || is_state_ref(operand),
            _ => return Err(format!("{key} is not a comparison")),
        };
        if !fits {
            return Err(format!("{key} has a value it cannot compare"));
        }
    }
    Ok(*source != "$state")
}

fn any_item(results: impl Iterator<Item = Checked>) -> Checked {
    let mut uses_item = false;
    for result in results {
        uses_item |= result?;
    }
    Ok(uses_item)
}

fn check_condition(value: &Value, depth: usize) -> Checked {
    if depth > catalog().limits.expression_depth {
        return Err("a condition nests too deep".into());
    }
    match value {
        Value::Bool(_) => Ok(false),
        Value::Array(list) if list.is_empty() => Err("a list of conditions cannot be empty".into()),
        Value::Array(list) => any_item(list.iter().map(check_single)),
        Value::Object(fields)
            if fields.len() == 1 && (fields.contains_key("$and") || fields.contains_key("$or")) =>
        {
            let list = fields
                .values()
                .next()
                .and_then(Value::as_array)
                .filter(|l| !l.is_empty())
                .ok_or("$and and $or take a list of conditions")?;
            any_item(list.iter().map(|c| check_condition(c, depth + 1)))
        }
        _ => check_single(value),
    }
}

fn check_expression(value: &Value, depth: usize) -> Checked {
    if depth > catalog().limits.expression_depth {
        return Err("an expression nests too deep".into());
    }
    let fields = value.as_object().ok_or("an expression is an object")?;
    let only = |key: &str| fields.len() == 1 && fields.contains_key(key);
    if only("$state") {
        return if is_state_ref(value) {
            Ok(false)
        } else {
            Err("$state must be a path like /form/plan".into())
        };
    }
    if only("$item") {
        return if fields["$item"].as_str().is_some_and(item_path) {
            Ok(true)
        } else {
            Err("$item must be a field of the item".into())
        };
    }
    if only("$index") {
        return if fields["$index"] == Value::Bool(true) {
            Ok(true)
        } else {
            Err("$index must be true".into())
        };
    }
    if only("$template") {
        let template = fields["$template"]
            .as_str()
            .filter(|t| t.encode_utf16().count() <= 4000)
            .ok_or("$template must be a string")?;
        return Ok(template
            .match_indices("${")
            .any(|(at, _)| !template[at + 2..].starts_with('/')));
    }
    if fields.len() == 3
        && ["$cond", "$then", "$else"]
            .iter()
            .all(|k| fields.contains_key(*k))
    {
        let branch = |operand: &Value| {
            if is_scalar(operand) {
                Ok(false)
            } else {
                check_expression(operand, depth + 1)
            }
        };
        let cond = check_condition(&fields["$cond"], depth + 1)?;
        return Ok(cond | branch(&fields["$then"])? | branch(&fields["$else"])?);
    }
    Err("only $state, $item, $index, $template and $cond are allowed".into())
}

fn check_state(value: &Value, depth: usize) -> Option<String> {
    let limits = &catalog().limits;
    if depth > limits.state_depth {
        return Some("state nests too deep".into());
    }
    match value {
        Value::Array(items) => {
            if items.len() > limits.repeat_items {
                return Some(format!(
                    "a list in state holds {} items at most",
                    limits.repeat_items
                ));
            }
            items.iter().find_map(|i| check_state(i, depth + 1))
        }
        Value::Object(fields) => fields.iter().find_map(|(key, item)| {
            if state_path(&format!("/{key}")) {
                check_state(item, depth + 1)
            } else {
                Some(format!("{key} cannot be a key in state"))
            }
        }),
        _ => None,
    }
}

/// `schema` without the props that hold expressions.
fn schema_without(schema: &Value, names: &[&str]) -> Value {
    let mut out = schema.clone();
    if let Some(properties) = out.get_mut("properties").and_then(Value::as_object_mut) {
        properties.retain(|k, _| !names.contains(&k.as_str()));
    }
    if let Some(required) = out.get_mut("required").and_then(Value::as_array_mut) {
        required.retain(|r| r.as_str().is_none_or(|k| !names.contains(&k)));
    }
    out
}

fn json_type_holds(ty: &str, value: &Value) -> bool {
    match ty {
        "string" => value.is_string(),
        "number" => value.is_number(),
        "integer" => value.as_f64().is_some_and(|n| n.fract() == 0.0),
        "boolean" => value.is_boolean(),
        "array" => value.is_array(),
        "object" => value.is_object(),
        "null" => value.is_null(),
        _ => false,
    }
}

fn limit(schema: &Value, keyword: &str) -> Option<f64> {
    schema.get(keyword).and_then(Value::as_f64)
}

/// `value` against the subset of JSON Schema the generated catalog uses.
/// The error is the path of the first thing that does not fit.
fn conforms(schema: &Value, value: &Value, path: &str) -> Result<(), String> {
    if let Some(options) = schema.get("anyOf").and_then(Value::as_array) {
        return if options.iter().any(|o| conforms(o, value, path).is_ok()) {
            Ok(())
        } else {
            Err(format!("{path}: no allowed form fits"))
        };
    }
    if let Some(allowed) = schema.get("enum").and_then(Value::as_array)
        && !allowed.contains(value)
    {
        return Err(format!("{path}: not one of the allowed values"));
    }
    if schema.get("const").is_some_and(|c| c != value) {
        return Err(format!("{path}: not the allowed value"));
    }
    if let Some(ty) = schema.get("type").and_then(Value::as_str)
        && !json_type_holds(ty, value)
    {
        return Err(format!("{path}: expected {ty}"));
    }
    match value {
        Value::String(s) => conforms_string(schema, s, path),
        Value::Number(_) => conforms_number(schema, value, path),
        Value::Array(items) => conforms_array(schema, items, path),
        Value::Object(fields) => conforms_object(schema, fields, path),
        _ => Ok(()),
    }
}

fn conforms_string(schema: &Value, s: &str, path: &str) -> Result<(), String> {
    // JavaScript measures a string in UTF-16 units; both validators must agree.
    let units = s.encode_utf16().count() as f64;
    if limit(schema, "minLength").is_some_and(|m| units < m) {
        return Err(format!("{path}: too short"));
    }
    if limit(schema, "maxLength").is_some_and(|m| units > m) {
        return Err(format!("{path}: too long"));
    }
    match schema.get("x-huginn-format").and_then(Value::as_str) {
        Some(format) if !format_holds(format, s) => Err(format!("{path}: not a valid {format}")),
        _ => Ok(()),
    }
}

fn conforms_number(schema: &Value, value: &Value, path: &str) -> Result<(), String> {
    let n = value.as_f64().unwrap_or(f64::NAN);
    let out = limit(schema, "minimum").is_some_and(|m| n < m)
        || limit(schema, "maximum").is_some_and(|m| n > m)
        || limit(schema, "exclusiveMinimum").is_some_and(|m| n <= m)
        || limit(schema, "exclusiveMaximum").is_some_and(|m| n >= m);
    if out {
        return Err(format!("{path}: out of range"));
    }
    Ok(())
}

fn conforms_array(schema: &Value, items: &[Value], path: &str) -> Result<(), String> {
    let len = items.len() as f64;
    if limit(schema, "minItems").is_some_and(|m| len < m) {
        return Err(format!("{path}: too few items"));
    }
    if limit(schema, "maxItems").is_some_and(|m| len > m) {
        return Err(format!("{path}: too many items"));
    }
    if let Some(item) = schema.get("items") {
        for (i, value) in items.iter().enumerate() {
            conforms(item, value, &format!("{path}.{i}"))?;
        }
    }
    Ok(())
}

fn conforms_object(schema: &Value, fields: &Map<String, Value>, path: &str) -> Result<(), String> {
    let empty = Map::new();
    let known = schema
        .get("properties")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    for required in schema
        .get("required")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
    {
        if !fields.contains_key(required) {
            return Err(format!("{path}.{required}: required"));
        }
    }
    for (name, value) in fields {
        match known.get(name) {
            Some(prop) => conforms(prop, value, &format!("{path}.{name}"))?,
            None if schema.get("additionalProperties") == Some(&Value::Bool(false)) => {
                return Err(format!("{path}.{name}: unknown prop"));
            }
            None => {}
        }
    }
    Ok(())
}

fn first_hidden(value: &Value) -> Option<String> {
    match value {
        Value::String(s) => hidden_chars_in(s, 1).into_iter().next(),
        Value::Array(items) => items.iter().find_map(first_hidden),
        Value::Object(fields) => fields.values().find_map(first_hidden),
        _ => None,
    }
}

fn lengths_agree(rule: &LengthRule, props: &Value) -> bool {
    let (Some(target), Some(list)) = (
        props.get(&rule.same_length_as).and_then(Value::as_array),
        props.get(&rule.list).and_then(Value::as_array),
    ) else {
        return false;
    };
    if rule.whole {
        return list.len() == target.len();
    }
    list.iter().all(|item| {
        let measured = rule.field.as_ref().map_or(Some(item), |f| item.get(f));
        measured
            .and_then(Value::as_array)
            .is_some_and(|m| m.len() == target.len())
    })
}

struct Element<'a> {
    kind: &'a str,
    component: &'static Component,
    props: &'a Value,
    children: Vec<&'a str>,
    uses_item: bool,
    repeats: bool,
}

fn check_element<'a>(key: &'a str, raw: &'a Value) -> Result<Element<'a>, Issue> {
    let refuse = |code, message: String| Err(issue(code, Some(key), message));
    if !answer_id(key) {
        return refuse(
            "bad_key",
            "an element key starts with a letter and holds letters, digits, - and _ (64 at most)"
                .into(),
        );
    }
    let Some(fields) = raw.as_object() else {
        return refuse("bad_envelope", "an element is an object".into());
    };
    let extra: Vec<&str> = fields
        .keys()
        .map(String::as_str)
        .filter(|f| !matches!(*f, "type" | "props" | "children" | "visible" | "repeat"))
        .collect();
    if !extra.is_empty() {
        return refuse(
            "unsupported_field",
            format!(
                "{} is not supported: a view has no actions or watchers",
                extra.join(", ")
            ),
        );
    }
    let Some(kind) = raw.get("type").and_then(Value::as_str) else {
        return refuse("bad_envelope", "type must be a component name".into());
    };
    let Some(component) = catalog().components.get(kind) else {
        return refuse(
            "unknown_component",
            format!("{kind} is not in the catalog; see harbard huginn catalog"),
        );
    };
    let props = raw.get("props").unwrap_or(&Value::Null);
    let known = component.props.get("properties").and_then(Value::as_object);
    let dynamic: Vec<&str> = props
        .as_object()
        .into_iter()
        .flatten()
        .filter(|(name, value)| {
            is_expression(value) && known.is_some_and(|k| k.contains_key(*name))
        })
        .map(|(name, _)| name.as_str())
        .collect();
    let mut uses_item = false;
    for name in &dynamic {
        if component.fixed.holds(name) {
            return refuse("fixed_prop", format!("{kind}.{name} must be a plain value"));
        }
        match check_expression(&props[*name], 1) {
            Ok(item) => uses_item |= item,
            Err(why) => return refuse("bad_expression", format!("{kind}.{name}: {why}")),
        }
    }
    let conformed = if dynamic.is_empty() {
        conforms(&component.props, props, kind)
    } else {
        let mut literal = props.clone();
        if let Some(fields) = literal.as_object_mut() {
            fields.retain(|k, _| !dynamic.contains(&k.as_str()));
        }
        conforms(&schema_without(&component.props, &dynamic), &literal, kind)
    };
    if let Err(why) = conformed {
        return refuse("bad_props", why);
    }
    if let Some(hidden) = first_hidden(props).or_else(|| raw.get("visible").and_then(first_hidden))
    {
        return refuse(
            "hidden_characters",
            format!("{kind} carries a character you cannot see ({hidden})"),
        );
    }
    let children: Vec<&str> = match raw.get("children") {
        None => Vec::new(),
        Some(Value::Array(list)) if list.iter().all(Value::is_string) => {
            list.iter().filter_map(Value::as_str).collect()
        }
        Some(_) => return refuse("bad_envelope", "children must be element keys".into()),
    };
    match &component.children {
        ChildRule::Arity(Arity::None) if !children.is_empty() => {
            return refuse("children_not_allowed", format!("{kind} takes no children"));
        }
        ChildRule::Arity(Arity::Some) if children.is_empty() => {
            return refuse(
                "children_required",
                format!("{kind} needs at least one child"),
            );
        }
        ChildRule::Match { same_length_as }
            if props
                .get(same_length_as)
                .and_then(Value::as_array)
                .map(Vec::len)
                != Some(children.len()) =>
        {
            return refuse(
                "children_mismatch",
                format!("{kind} needs one child per item of {same_length_as}"),
            );
        }
        _ => {}
    }
    for rule in &component.lengths {
        if dynamic.contains(&rule.list.as_str()) || dynamic.contains(&rule.same_length_as.as_str())
        {
            continue;
        }
        if !lengths_agree(rule, props) {
            return refuse(
                "length_mismatch",
                format!(
                    "{kind}.{} must match {} in length",
                    rule.list, rule.same_length_as
                ),
            );
        }
    }
    let repeats = match raw.get("repeat") {
        None => false,
        Some(repeat) if repeat_is_sound(repeat, component) => true,
        Some(_) => {
            return refuse(
                "bad_repeat",
                format!(
                    "{kind}: repeat is {{ statePath, key? }} on a component that takes children"
                ),
            );
        }
    };
    let visible_item = match raw.get("visible").map(|v| check_condition(v, 1)) {
        None => false,
        Some(Ok(item)) => item,
        Some(Err(why)) => return refuse("bad_condition", format!("{kind}.visible: {why}")),
    };
    Ok(Element {
        kind,
        component,
        props,
        children,
        uses_item: uses_item || (visible_item && !repeats),
        repeats,
    })
}

fn repeat_is_sound(repeat: &Value, component: &Component) -> bool {
    let Some(fields) = repeat.as_object() else {
        return false;
    };
    matches!(component.children, ChildRule::Arity(Arity::Some))
        && fields.keys().all(|k| k == "statePath" || k == "key")
        && fields
            .get("statePath")
            .and_then(Value::as_str)
            .is_some_and(state_path)
        && fields
            .get("key")
            .is_none_or(|k| k.as_str().is_some_and(|k| state_path(&format!("/{k}"))))
}

fn check_shape(root: &str, elements: &HashMap<&str, Element<'_>>, issues: &mut Vec<Issue>) -> bool {
    if !elements.contains_key(root) {
        issues.push(issue(
            "root_not_found",
            Some(root),
            format!("root {root} is not among the elements"),
        ));
        return false;
    }
    let mut parents: HashSet<&str> = HashSet::new();
    let mut sound = true;
    for (key, element) in elements {
        for child in &element.children {
            if !elements.contains_key(child) {
                issues.push(issue(
                    "missing_child",
                    Some(key),
                    format!("child {child} is not among the elements"),
                ));
                sound = false;
            } else if *child == root || !parents.insert(child) {
                issues.push(issue(
                    "shared_child",
                    Some(child),
                    format!("{child} has more than one parent, or is the root and a child"),
                ));
                sound = false;
            }
        }
    }
    sound
}

struct Walk<'a, 'e> {
    elements: &'e HashMap<&'a str, Element<'a>>,
    seen: HashSet<&'a str>,
    answer_ids: HashSet<&'a str>,
    issues: Vec<Issue>,
}

fn walk<'a>(
    key: &'a str,
    state: &mut Walk<'a, '_>,
    depth: usize,
    inside_answer: bool,
    in_repeat: bool,
    form_fields: Option<&mut HashSet<&'a str>>,
) {
    let Some(element) = state.elements.get(key) else {
        return;
    };
    state.seen.insert(key);
    let limits = &catalog().limits;
    if depth > limits.depth {
        state.issues.push(issue(
            "too_deep",
            Some(key),
            format!("a view nests {} levels at most", limits.depth),
        ));
        return;
    }
    if element.uses_item && !in_repeat {
        state.issues.push(issue(
            "item_outside_repeat",
            Some(key),
            "$item and $index only work inside a repeat".into(),
        ));
    }
    if in_repeat && element.component.fixed.is_all() {
        state.issues.push(issue(
            "interactive_in_repeat",
            Some(key),
            format!(
                "{} cannot be repeated: it needs a place of its own",
                element.kind
            ),
        ));
    }
    if element.repeats {
        if in_repeat {
            state.issues.push(issue(
                "nested_repeat",
                Some(key),
                "a repeat cannot sit inside another".into(),
            ));
        }
        if count_below(element, state.elements) > limits.repeat_elements {
            state.issues.push(issue(
                "repeat_too_large",
                Some(key),
                format!("a repeat holds {} elements at most", limits.repeat_elements),
            ));
        }
    }
    let mut form_fields = form_fields;
    if element.component.inside_form {
        let id = element
            .props
            .get("id")
            .and_then(Value::as_str)
            .unwrap_or_default();
        match form_fields.as_deref_mut() {
            None => state.issues.push(issue(
                "outside_form",
                Some(key),
                format!("{} only works inside a Form", element.kind),
            )),
            Some(fields) => {
                if !fields.insert(id) {
                    state.issues.push(issue(
                        "duplicate_field_id",
                        Some(key),
                        format!("two fields of one Form use the id {id}"),
                    ));
                }
            }
        }
    }
    if element.component.answers {
        if inside_answer {
            state.issues.push(issue(
                "nested_answer",
                Some(key),
                format!("{} cannot sit inside another Form", element.kind),
            ));
        }
        let id = element
            .props
            .get("id")
            .and_then(Value::as_str)
            .unwrap_or_default();
        if !state.answer_ids.insert(id) {
            state.issues.push(issue(
                "duplicate_answer_id",
                Some(key),
                format!("two components answer as {id}"),
            ));
        }
    }
    let inside = inside_answer || element.component.answers;
    let repeating = in_repeat || element.repeats;
    if element.kind == "Form" {
        let mut own = HashSet::new();
        for child in &element.children {
            walk(child, state, depth + 1, inside, repeating, Some(&mut own));
        }
    } else {
        for child in &element.children {
            walk(
                child,
                state,
                depth + 1,
                inside,
                repeating,
                form_fields.as_deref_mut(),
            );
        }
    }
}

fn count_below(element: &Element<'_>, elements: &HashMap<&str, Element<'_>>) -> usize {
    element
        .children
        .iter()
        .filter_map(|key| elements.get(key))
        .map(|child| 1 + count_below(child, elements))
        .sum()
}

/// Check a view. On success, the files it names, which must travel with it.
pub fn validate(source: &[u8]) -> Result<Vec<String>, Vec<Issue>> {
    let fail = |code, message: String| vec![issue(code, None, message)];
    let limits = &catalog().limits;
    if source.len() > limits.bytes {
        return Err(fail(
            "too_large",
            format!("a view holds {} bytes at most", limits.bytes),
        ));
    }
    let raw: Value = serde_json::from_slice(source)
        .map_err(|_| fail("invalid_json", "a view is one JSON document".into()))?;
    let bad_envelope = || {
        fail(
            "bad_envelope",
            "a view is { root, elements } and nothing else".into(),
        )
    };
    let fields = raw.as_object().ok_or_else(bad_envelope)?;
    if fields
        .keys()
        .any(|k| k != "root" && k != "elements" && k != "state")
    {
        return Err(bad_envelope());
    }
    if let Some(state) = fields.get("state") {
        if !state.is_object() {
            return Err(fail("bad_state", "state is an object".into()));
        }
        if let Some(problem) = check_state(state, 1) {
            return Err(fail("bad_state", problem));
        }
        if let Some(hidden) = first_hidden(state) {
            return Err(fail(
                "hidden_characters",
                format!("state carries a character you cannot see ({hidden})"),
            ));
        }
    }
    let root = fields
        .get("root")
        .and_then(Value::as_str)
        .ok_or_else(bad_envelope)?;
    let raw_elements = fields
        .get("elements")
        .and_then(Value::as_object)
        .ok_or_else(bad_envelope)?;
    if raw_elements.is_empty() {
        return Err(fail(
            "bad_envelope",
            "a view has at least one element".into(),
        ));
    }
    if raw_elements.len() > limits.elements {
        return Err(fail(
            "too_many_elements",
            format!("a view holds {} elements at most", limits.elements),
        ));
    }
    let mut issues = Vec::new();
    let mut elements = HashMap::new();
    for (key, element) in raw_elements {
        match check_element(key, element) {
            Ok(checked) => {
                elements.insert(key.as_str(), checked);
            }
            Err(found) => issues.push(found),
        }
    }
    let capped = |mut issues: Vec<Issue>| {
        issues.truncate(MAX_ISSUES);
        issues
    };
    if !issues.is_empty() {
        return Err(capped(issues));
    }
    if !check_shape(root, &elements, &mut issues) {
        return Err(capped(issues));
    }
    let mut state = Walk {
        elements: &elements,
        seen: HashSet::new(),
        answer_ids: HashSet::new(),
        issues,
    };
    walk(root, &mut state, 1, false, false, None);
    for key in elements.keys() {
        if !state.seen.contains(key) {
            state.issues.push(issue(
                "orphan",
                Some(key),
                format!("{key} is not reachable from the root"),
            ));
        }
    }
    if !state.issues.is_empty() {
        return Err(capped(state.issues));
    }
    let mut files: Vec<String> = Vec::new();
    for element in elements.values() {
        for prop in &element.component.files {
            if let Some(name) = element.props.get(prop).and_then(Value::as_str)
                && !files.iter().any(|f| f == name)
            {
                files.push(name.to_string());
            }
        }
    }
    files.sort();
    Ok(files)
}

fn read_capped(path: &Path) -> Result<Vec<u8>, String> {
    let file = std::fs::File::open(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut buf = Vec::new();
    file.take(catalog().limits.bytes as u64 + 1)
        .read_to_end(&mut buf)
        .map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(buf)
}

fn cmd_check(path: &Path, as_json: bool) -> i32 {
    let bytes = match read_capped(path) {
        Ok(bytes) => bytes,
        Err(e) => {
            eprintln!("refused: {e}");
            return 2;
        }
    };
    match validate(&bytes) {
        Ok(files) => {
            if as_json {
                println!("{}", json!({ "ok": true, "files": files }));
            } else if files.is_empty() {
                println!("view is valid");
            } else {
                println!(
                    "view is valid; attach it together with: {}",
                    files.join(", ")
                );
            }
            0
        }
        Err(issues) => {
            if as_json {
                let list: Vec<Value> = issues
                    .iter()
                    .map(|i| json!({ "code": i.code, "element": i.element, "message": i.message }))
                    .collect();
                println!("{}", json!({ "ok": false, "issues": list }));
            } else {
                for found in &issues {
                    eprintln!("{}", describe(std::slice::from_ref(found)));
                }
            }
            2
        }
    }
}

/// `harbard huginn …`.
pub fn cmd_huginn(action: &HuginnAction, as_json: bool) -> i32 {
    match action {
        HuginnAction::Catalog => {
            print!("{GUIDE}");
            0
        }
        HuginnAction::Check { path } => cmd_check(path, as_json),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const VALID: &str = include_str!("../../../packages/huginn/fixtures/valid.json");
    const INVALID: &str = include_str!("../../../packages/huginn/fixtures/invalid.json");

    fn cases(source: &str) -> Vec<Value> {
        serde_json::from_str::<Value>(source)
            .unwrap()
            .as_array()
            .unwrap()
            .clone()
    }

    fn check(view: &Value) -> Result<Vec<String>, Vec<Issue>> {
        validate(view.to_string().as_bytes())
    }

    #[test]
    fn every_valid_fixture_is_accepted_by_rust_too() {
        for case in cases(VALID) {
            let name = case["name"].as_str().unwrap();
            if let Err(issues) = check(&case["view"]) {
                panic!("{name}: {}", describe(&issues));
            }
        }
    }

    #[test]
    fn every_invalid_fixture_is_refused_with_the_same_code_as_typescript() {
        for case in cases(INVALID) {
            let name = case["name"].as_str().unwrap();
            let expected = case["expect"].as_str().unwrap();
            let issues = check(&case["view"]).expect_err(name);
            assert!(
                issues.iter().any(|i| i.code == expected),
                "{name}: expected {expected}, got {}",
                describe(&issues)
            );
        }
    }

    #[test]
    fn text_that_is_not_json_is_refused() {
        let issues = validate(b"{ not json").unwrap_err();
        assert_eq!(issues[0].code, "invalid_json");
    }

    #[test]
    fn a_view_over_the_byte_limit_is_refused() {
        let big = vec![b' '; catalog().limits.bytes + 1];
        assert_eq!(validate(&big).unwrap_err()[0].code, "too_large");
    }

    #[test]
    fn a_valid_view_names_the_files_it_shows() {
        let view = json!({"root":"a","elements":{"a":{"type":"BeforeAfter","props":{"before":"a.png","after":"b.png"}}}});
        assert_eq!(check(&view).unwrap(), ["a.png", "b.png"]);
    }
}
